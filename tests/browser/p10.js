async function start() {
  const state = document.querySelector("#fixture-state");
  state.textContent = english ? "Preparing local resources…" : "جارٍ تجهيز الموارد المحلية…";
  const host = document.querySelector("#fixture-host");
  const article = makeArticle(await integrityFor(assetUrl));
  const engine = createIntuiEngine({ validateArticle });
  registerArticleRenderer(engine);
  const handle = engine.mount(host, article, { document, theme: "system" });
  const mounted = await handle.ready;
  await new Promise((resolve) => setTimeout(resolve, 80));
  const root = host.shadowRoot;
  const image = root.querySelector("#scene-demo img");
  if (image?.getAttribute("data-integrity-state") === "pending") {
    await new Promise((resolve, reject) => {
      const observer = new MutationObserver(() => {
        const result = image.getAttribute("data-integrity-state");
        if (result === "verified" || result === "failed") { observer.disconnect(); resolve(); }
      });
      observer.observe(image, { attributes: true, attributeFilter: ["data-integrity-state"] });
      setTimeout(() => { observer.disconnect(); reject(new Error("Image integrity verification timed out")); }, 5000);
    });
  }
  window.__p10 = { article, engine, handle, root, image };
  window.__p10Audit = {
    mount: mounted.status,
    locale,
    direction: root.querySelector(".if-article-root").dir,
    imageIntegrity: image?.getAttribute("data-integrity-state"),
    localAssetOrigin: new URL(image?.getAttribute("src") || assetUrl, location.href).origin,
    captionTracks: root.querySelectorAll("track").length,
    transcripts: root.querySelectorAll(".if-media-transcript p").length,
    audioAndVideo: root.querySelectorAll("audio[controls],video[controls]").length,
    mathMarkup: root.querySelectorAll("math").length,
    mathFallback: Boolean(root.querySelector("#equation-error [role=status]")),
    codeCopy: Boolean(root.querySelector("#code-demo [data-copy-code]")),
    numberedCitation: root.querySelector("#source-citation a")?.textContent,
    focusableHotspots: root.querySelectorAll(".if-image-hotspot[aria-label]").length,
  };
  state.textContent = mounted.status === "ready"
    ? (english ? "Ready: local assets are integrity checked." : "جاهز: الأصول محلية والترميز محقّق.")
    : `${english ? "Could not start" : "تعذّر الإقلاع"}: ${mounted.status}`;
  if (mounted.status !== "ready") throw new Error(`P10 renderer did not mount: ${JSON.stringify(mounted)}`);
}

start().catch((error) => {
  document.querySelector("#fixture-state").textContent = `${english ? "Setup error" : "خطأ في التهيئة"}: ${error.message}`;
  window.__p10Audit = { error: error.message };
});
